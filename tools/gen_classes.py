#!/usr/bin/env python3
"""Emit the Unicode character classes the GPT-2 split needs, as ranges.

The pre-tokenizer pattern is

    's|'t|'re|'ve|'m|'ll|'d| ?\\p{L}+| ?\\p{N}+| ?[^\\s\\p{L}\\p{N}]+|\\s+(?!\\S)|\\s+

so three classes decide every split: letter, number, and whitespace.
Written by hand that is three tables of a few hundred ranges each and
several hundred chances to be wrong somewhere nobody looks. Derived from
Python's own unicodedata they are a script, and the Unicode version is
recorded in the output so a disagreement can be attributed.

A caveat worth stating in the generated file rather than hiding here:
the reference implementation gets its tables from the Rust regex crate,
which tracks its own Unicode version. If that differs from Python's,
the two disagree on codepoints assigned between the versions. The
corpus comparison is what would find it, and that is the right place
for it to be found.

Run: python3 tools/gen_classes.py > classes.h
"""
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:      # surrogates are never text
            hit = False
        else:
            hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print("static const CpRange %s[] = {" % name)
    for lo, hi in rs:
        print("\t{ 0x%04X, 0x%04X }," % (lo, hi))
    print("};")
    print("#define %s_N (sizeof %s / sizeof *%s)" % (name.upper(), name, name))
    print()


def main():
    cat = unicodedata.category

    # \s in the Rust regex crate is Unicode White_Space, which is a
    # property and not a category, so it is listed rather than derived:
    # the set is small, fixed, and in PropList.txt.
    ws = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680,
          0x2028, 0x2029, 0x202F, 0x205F, 0x3000}
    ws |= set(range(0x2000, 0x200B))

    print("/* Generated by tools/gen_classes.py. Do not edit.")
    print(" * Unicode %s, from Python's unicodedata." % unicodedata.unidata_version)
    print(" *")
    print(" * The reference implementation's tables come from the Rust regex")
    print(" * crate and track its own Unicode version. Where the two differ,")
    print(" * they differ on codepoints assigned between those versions, and")
    print(" * the corpus comparison in t/run.sh is what finds it.")
    print(" */")
    print("typedef struct { unsigned lo, hi; } CpRange;")
    print()
    emit("uni_letter", ranges(lambda c: cat(chr(c)).startswith("L")))
    emit("uni_number", ranges(lambda c: cat(chr(c)).startswith("N")))
    emit("uni_space", ranges(lambda c: c in ws))


main()
